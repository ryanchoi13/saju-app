def validate_paragraph(text: str, allow_absolute: bool = False) -> list[str]:
    """문단 하나를 스펙 §1·§2 규칙으로 검사해 위반 목록을 돌려준다. 비어 있으면 통과."""
    issues: list[str] = []
    text = text or ""
    for word in BANNED_PERSONALITY:
        if word in text:
            issues.append(f"사건 단정어 '{word}'")
    emphasis = sum(text.count(w) for w in EMPHASIS_WORDS)
    if emphasis > 1:
        issues.append(f"강조어 {emphasis}회")
    if not allow_absolute and any(w in text for w in ABSOLUTE_WORDS):
        issues.append("결핍 단정어(아예·전혀 없음)")
    for sentence in split_sentences(text):
        if len(sentence) > SENTENCE_MAX:
            issues.append(f"문장이 깁니다({len(sentence)}): {sentence}")
    banned = find_banned(text)
    if banned:
        issues.append(f"금기어 {banned}")
    medical = find_medical(text)
    if medical:
        issues.append(f"의학 표현 {medical}")
    return issues
