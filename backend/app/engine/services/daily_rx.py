def _rows(element: str, kind: str) -> tuple[tuple[str, str, str], ...]:
    """(장면, 변형, 문장) 행. 근거·분야 은행은 장면·변형이 없다."""
    if kind == "evidence":
        return tuple(("", "", t) for t in EVIDENCE[element])
    if kind in ("주의", "좋음"):
        return tuple(("", "", t) for t in DOMAIN[element][kind])
    return tuple(BANK[element][kind])


def _variant_ok(variant: str, d: date) -> bool:
    if variant == "weekday":
        return d.weekday() < 5
    if variant == "weekend":
        return d.weekday() >= 5
    if variant == "season":
        return d.month in (10, 11, 12, 1, 2)
    return True


_STEM_STOP = {"오늘", "내일", "하나", "한번", "평소", "먼저", "바로", "그냥", "같이", "함께", "보세", "두세", "하세", "마세"}


def _stems(text: str) -> set[str]:
    """낱말 앞 두 글자(겹침 검사용). '서운함을'·'서운한' → '서운'."""
    return {w[:2] for w in text.replace(".", "").split() if len(w) >= 2} - _STEM_STOP


def _seed(account_key: str, d: date, element: str, kind: str) -> int:
    return int(hashlib.sha256(f"{account_key}|{d.isoformat()}|{element}|{kind}".encode()).hexdigest(), 16)


def pick(account_key: str, d: date, element: str, kind: str,
         recent: list[tuple[str, str, int]], scene: str | None = None,
         blocked_scenes: set[str] | None = None, prefer_scene: str | None = None,
         avoid_head: str | None = None, recent_week: list[tuple[str, str, int]] | None = None,
         avoid_words: set[str] | None = None) -> tuple[int, str]:
    """계정·날짜 시드로 결정론적으로 문장 하나를 고른다.

    recent = 최근 30일 사용 목록 [(요소, 구분, 번호)] (오래된 것부터). 변형 조건(평일·주말·계절)에 맞는 후보 중
    최근 목록에 없는 것을 시드 위치부터 돌려 고르고, 전부 썼으면 가장 오래전에 쓴 것을 다시 쓴다.
    scene 을 주면('할 것'을 고를 때 '하지 말 것'의 장면) 같은 장면 문장을 앞에 세운다.
    """
    rows = _rows(element, kind)
    cand = [i for i, (_, v, _) in enumerate(rows) if _variant_ok(v, d)] or list(range(len(rows)))
    if blocked_scenes:
        cand = [i for i in cand if rows[i][0] not in blocked_scenes] or cand
    if avoid_head:   # 11/10: '하지 말 것'과 '할 것'이 같은 첫마디("쌀쌀한 날…")로 시작하지 않게
        cand = [i for i in cand if rows[i][2].split()[0] != avoid_head] or cand
    if prefer_scene and any(rows[i][0] == prefer_scene for i in cand) and not scene:
        scene = prefer_scene
    if scene and any(rows[i][0] == scene for i in cand):
        # 11/12: 장면이 정해졌으면 그 장면 안에서만 고른다. 예전엔 장면 문장을 최근에 썼으면 다른 장면으로 넘어가서,
        # 홈 '오늘은 이렇게'가 자세히 보기의 이야기(튀는 분야)와 다른 말을 했다. 반복은 장면 안 LRU 로 처리.
        in_scene = [i for i in cand if rows[i][0] == scene]
        week = {i for (e, k, i) in (recent_week or []) if e == element and k == kind}
        if any(i not in week for i in in_scene):
            cand = in_scene
        else:                             # 장면 문장을 이번 주에 이미 썼으면 같은 말 되풀이보다 다른 장면(막힌 장면 제외)
            cand = in_scene + [i for i in cand if rows[i][0] != scene]
    else:
        shift = _seed(account_key, d, element, kind) % len(cand)
        cand = cand[shift:] + cand[:shift]
    if avoid_words:   # 11/12: '할 것'이 '하지 말 것'과 같은 낱말("서운…", "연락…")을 되풀이하지 않게 뒤로 보낸다
        cand = [i for i in cand if not (_stems(rows[i][2]) & avoid_words)] + [i for i in cand if _stems(rows[i][2]) & avoid_words]
    used = [i for (e, k, i) in recent if e == element and k == kind]
    fresh = [i for i in cand if i not in used]
    if fresh:
        idx = fresh[0]
    else:
        last_pos = {i: max(p for p, (e, k, j) in enumerate(recent) if (e, k, j) == (element, kind, i)) for i in cand}
        idx = min(cand, key=lambda i: last_pos[i])
    return idx, rows[idx][2]


def spine_item(items: list[tuple[str, int]], grade: str | None) -> tuple[str, int] | None:
    """하루의 줄기(11/9 정오님: 칸끼리 앞뒤가 안 맞는다). 제목·총운·'오늘은 이런 날'·'오늘은 이렇게'가 모두 이 요소에서 나온다.

    등급과 같은 방향의 가장 센 요소를 줄기로 삼는다(좋음 이상 = 가장 센 길 요소, 주의 이하 = 가장 센 흉 요소).
    예전에는 칸마다 따로 골라서, 좋음 81점인 날에도 '가장 센 요소'인 시지 충(−8)이 근거·제목을 잡고
    처방은 가장 센 길 요소(결핍 채움)로 가 서로 다른 이야기를 했다. 반대 방향 요소는 총운의 '다만' 문장으로 간다.
    같은 방향에 |w|≥4 요소가 없거나 보통 날이면 예전처럼 가장 센 요소.
    """
    if not items:
        return None
    if grade in LUCKY_GRADES:
        pos = [x for x in items if x[1] >= 4]
        if pos:
            return max(pos, key=lambda x: x[1])
    if grade in CAUTION_GRADES:
        neg = [x for x in items if x[1] <= -4]
        if neg:
            return min(neg, key=lambda x: x[1])
    return daily_score.top_item(items)


def evidence_key(items: list[tuple[str, int]], grade: str | None = None) -> str:
    """근거 2문장의 요소 = 하루의 줄기. |w|<4 이거나 해·파만이면 '잔잔'."""
    if daily_score.confidence(items) == "약":
        return "잔잔"
    name = spine_item(items, grade)[0]
    return EVIDENCE_ALIAS.get(name, name)


def rx_element(items: list[tuple[str, int]], grade: str, standout: tuple[str, str] | None) -> str | None:
    """'오늘은 이렇게'의 은행 요소. 보통 날은 None."""
    if grade in CAUTION_GRADES:
        for name, w in sorted(items, key=lambda x: x[1]):
            if w >= 0:
                break
            key = CAUTION_MAP.get(EVIDENCE_ALIAS.get(name, name))
            if key:
                if key in ("day_clash", "month_clash", "day_punish") and standout == ("금전", "주의"):
                    return "wealth_hit"           # 충·형 맞은 글자가 재성이라 금전이 튀는 날
                return key
        return None
    if grade in LUCKY_GRADES:
        for name, w in sorted(items, key=lambda x: -x[1]):
            if w <= 0:
                break
            key = LUCKY_MAP.get(EVIDENCE_ALIAS.get(name, name))
            if key:
                return key
    return None


SCENE_DOMAIN = {"돈": "금전", "일": "일", "사람": "애정·관계", "몸": "건강"}   # '말'·'이동'은 분야 없음
DOMAIN_SCENE = {v: k for k, v in SCENE_DOMAIN.items()}


def rx_scene_rules(grade: str, tiers: dict[str, str] | None, standout: tuple[str, str] | None) -> tuple[set[str], str | None]:
    """처방 장면 규칙(11/9). 등급과 반대로 가는 분야(좋은 날의 주의 분야, 나쁜 날의 좋음 분야)를 말하는 장면은 막고,
    튀는 분야가 등급과 같은 방향이면 그 분야 장면을 앞세운다."""
    if not tiers:
        return set(), None
    against = "주의" if grade in LUCKY_GRADES else ("좋음" if grade in CAUTION_GRADES else None)
    blocked = {DOMAIN_SCENE[dom] for dom, t in tiers.items() if against and t == against and dom in DOMAIN_SCENE}
    if "사람" in blocked:
        blocked.add("말")                 # 11/12: '말' 장면(부탁·고마움 전하기)도 사람 일이라 함께 막는다
    prefer = None
    if standout:
        dom = {"사람": "애정·관계"}.get(standout[0], standout[0])
        if (standout[1] == "좋음") == (grade in LUCKY_GRADES) and dom in DOMAIN_SCENE:
            prefer = DOMAIN_SCENE[dom]
    if prefer is None and grade in LUCKY_GRADES | CAUTION_GRADES:
        # 11/12: 카드 standout 이 없어도 이야기에서 등급 쪽으로 기운 분야가 있으면 그 분야를 말한다(일 → 금전 → 애정·관계 → 건강)
        along = "좋음" if grade in LUCKY_GRADES else "주의"
        for dom in ("일", "금전", "애정·관계", "건강"):
            if tiers.get(dom) == along:
                prefer = DOMAIN_SCENE[dom]
                break
    return blocked, prefer


def compose_rx(account_key: str, d: date, element: str,
               recent: list[tuple[str, str, int]], blocked_scenes: set[str] | None = None,
               prefer_scene: str | None = None,
               recent_week: list[tuple[str, str, int]] | None = None) -> tuple[str, list[tuple[str, str, int]]]:
    """하지 말 것 1 + 할 것 1 (같은 장면을 앞세움). (문장, 이번에 쓴 [(요소, 구분, 번호)]) 를 돌려준다."""
    i, dont = pick(account_key, d, element, "dont", recent, blocked_scenes=blocked_scenes, prefer_scene=prefer_scene,
                   recent_week=recent_week)
    scene = BANK[element]["dont"][i][0]
    j, do = pick(account_key, d, element, "do", recent, scene=scene, blocked_scenes=blocked_scenes,
                 avoid_head=dont.split()[0], recent_week=recent_week, avoid_words=_stems(dont))
    return f"{dont} {do}", [(element, "dont", i), (element, "do", j)]


def select_for_day(core: MyeongriCoreResult, account_key: str, d: date,
                   recent: list[tuple[str, str, int]], evaluation: dict | None = None,
                   recent_week: list[tuple[str, str, int]] | None = None) -> dict:
    """하루치 문장 선택. recent 는 그 전 30일에 쓴 (요소, 구분, 번호) 목록(카드 문장 + 이야기 변형이 같은 목록에 섞인다).

    돌려주는 uses 는 카드 문장 몫, story_uses 는 오늘의 이야기(daily_story) 몫. 이력(_history)은 둘 다 쌓는다.
    이야기 조립이 실패하면 story 는 None 이고(daily.py 가 예전 이야기로 대신한다) 카드는 그대로 나간다.
    """
    ev = evaluation or daily_score.evaluate(core, daily_score.day_ganji(d), d)
    uses: list[tuple[str, str, int]] = []
    key = evidence_key(ev["items"], ev["grade"])
    i, evidence_text = pick(account_key, d, key, "evidence", recent)
    uses.append((key, "evidence", i))
    element = rx_element(ev["items"], ev["grade"], ev["standout"])
    rx_text, rx_scene = None, None
    if element:
        from app.engine.services.daily_story import rule_tiers   # 순환 import 방지
        blocked, prefer = rx_scene_rules(ev["grade"], rule_tiers(ev), ev["standout"])
        rx_text, used = compose_rx(account_key, d, element, recent, blocked, prefer, recent_week)
        uses.extend(used)
        rx_scene = BANK[element]["dont"][used[0][2]][0]
    domain_note = None
    if ev["standout"]:
        domain, kind = ev["standout"]
        j, text = pick(account_key, d, domain, kind, recent)
        uses.append((domain, kind, j))
        domain_note = {"domain": domain, "kind": kind, "text": text}
    out = {"evaluation": ev, "evidence_key": key, "evidence_text": evidence_text,
           "rx_element": element, "rx_text": rx_text, "rx_scene": rx_scene, "domain_note": domain_note, "uses": uses,
           "story": None, "story_uses": []}
    try:
        from app.engine.services import daily_story          # 순환 import 방지(daily_story 가 이 모듈을 읽는다)
        story = daily_story.build_story(core, ev, out, account_key, d, core.input.gender, recent)
        out["story"], out["story_uses"] = story, story["uses"]
    except Exception:                                         # noqa: BLE001 — 이야기 실패가 카드를 막지 않게
        logger.exception("daily_story 조립 실패 %s %s", account_key, d)
    return out


def _history(core: MyeongriCoreResult, account_key: str, start: date, until: date) -> list[tuple[date, tuple[str, str, int]]]:
    """start ~ until(포함) 의 선택 기록을 같은 규칙으로 다시 돌려 복원한다. 계정별로 캐시해 하루씩 이어 붙인다."""
    cache_key = (account_key, repr(core.input))
    cached = _HISTORY_CACHE.get(cache_key)
    if cached and cached["start"] <= start:
        history, cursor = cached["history"], cached["until"]
    else:
        history, cursor = [], start - timedelta(days=1)
    day = cursor + timedelta(days=1)
    while day <= until:
        recent = [u for day_used, u in history if day_used >= day - timedelta(days=RECENT_DAYS)]
        week = [u for day_used, u in history if day_used >= day - timedelta(days=WEEK_DAYS)]
        picked = select_for_day(core, account_key, day, recent, recent_week=week)
        history.extend((day, u) for u in picked["uses"] + picked["story_uses"])
        day += timedelta(days=1)
    if len(_HISTORY_CACHE) >= 2048:
        _HISTORY_CACHE.clear()
    _HISTORY_CACHE[cache_key] = {"start": min(start, cached["start"]) if cached and cached["start"] <= start else start,
                                 "until": max(until, cursor), "history": history}
    return history


def render_day(core: MyeongriCoreResult, account_key: str, d: date, evaluation: dict | None = None) -> dict:
    """오늘 문장. 최근 30일 목록은 저장 없이 RX_EPOCH(또는 60일 전) 부터 지난날을 같은 규칙으로 다시 돌려 복원한다.

    시작점을 날짜마다 옮기면(어제는 60일 전부터, 오늘은 59일 전부터) 어제의 복원이 어제 실제로 보인 것과 어긋나
    같은 문장이 이틀 연속 나올 수 있다. 고정된 시작점에서 돌리면 어느 날 계산해도 지난날이 같게 복원된다.
    기록은 계정별 캐시에 하루씩 이어 붙이므로 하루 한 번만 늘어난다(저장이 생기면 그 테이블로 바꾼다).
    """
    cache_key = (account_key, repr(core.input), d.isoformat())
    if cache_key in _RENDER_CACHE:
        return dict(_RENDER_CACHE[cache_key])
    start = min(RX_EPOCH, d - timedelta(days=RECENT_DAYS + REPLAY_WARMUP))
    history = _history(core, account_key, start, d - timedelta(days=1))
    recent = [u for day_used, u in history if d - timedelta(days=RECENT_DAYS) <= day_used < d]
    week = [u for day_used, u in history if d - timedelta(days=WEEK_DAYS) <= day_used < d]
    result = select_for_day(core, account_key, d, recent, evaluation, recent_week=week)
    if len(_RENDER_CACHE) >= 4096:
        _RENDER_CACHE.clear()
    _RENDER_CACHE[cache_key] = dict(result)
    return result


_RENDER_CACHE: dict[tuple, dict] = {}
_HISTORY_CACHE: dict[tuple, dict] = {}


def all_sentences() -> list[tuple[str, str]]:
    """검사용: 은행의 모든 문단 (출처, 문단)."""
    out = [(f"EVIDENCE[{k}][{i}]", t) for k, rows in EVIDENCE.items() for i, t in enumerate(rows)]
    out += [(f"DOMAIN[{d}][{k}][{i}]", t) for d, kinds in DOMAIN.items() for k, rows in kinds.items() for i, t in enumerate(rows)]
    out += [(f"BANK[{e}][{k}][{i}]", t) for e, data in BANK.items() for k in ("dont", "do") for i, (_, _, t) in enumerate(data[k])]
    return out
