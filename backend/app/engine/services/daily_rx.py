def _rows(element: str, kind: str) -> tuple[tuple[str, str, str], ...]:
    """(장면, 변형, 문장) 행. 근거·분야 은행은 장면·변형이 없다."""
    if kind == "evidence":
        return tuple(("", "", t) for t in EVIDENCE[element])
    if kind in ("주의", "좋음"):
        return tuple(("", "", t) for t in DOMAIN[element][kind])
    return tuple(BANK[element][kind])


def _variant_ok(variant: str, d: date) -> bool:
    if variant == "weekday":
        return d.weekday() < 5
    if variant == "weekend":
        return d.weekday() >= 5
    if variant == "season":
        return d.month in (10, 11, 12, 1, 2)
    return True


def _seed(account_key: str, d: date, element: str, kind: str) -> int:
    return int(hashlib.sha256(f"{account_key}|{d.isoformat()}|{element}|{kind}".encode()).hexdigest(), 16)


def pick(account_key: str, d: date, element: str, kind: str,
         recent: list[tuple[str, str, int]], scene: str | None = None) -> tuple[int, str]:
    """계정·날짜 시드로 결정론적으로 문장 하나를 고른다.

    recent = 최근 30일 사용 목록 [(요소, 구분, 번호)] (오래된 것부터). 변형 조건(평일·주말·계절)에 맞는 후보 중
    최근 목록에 없는 것을 시드 위치부터 돌려 고르고, 전부 썼으면 가장 오래전에 쓴 것을 다시 쓴다.
    scene 을 주면('할 것'을 고를 때 '하지 말 것'의 장면) 같은 장면 문장을 앞에 세운다.
    """
    rows = _rows(element, kind)
    cand = [i for i, (_, v, _) in enumerate(rows) if _variant_ok(v, d)] or list(range(len(rows)))
    if scene and any(rows[i][0] == scene for i in cand):
        cand = [i for i in cand if rows[i][0] == scene] + [i for i in cand if rows[i][0] != scene]
    else:
        shift = _seed(account_key, d, element, kind) % len(cand)
        cand = cand[shift:] + cand[:shift]
    used = [i for (e, k, i) in recent if e == element and k == kind]
    fresh = [i for i in cand if i not in used]
    if fresh:
        idx = fresh[0]
    else:
        last_pos = {i: max(p for p, (e, k, j) in enumerate(recent) if (e, k, j) == (element, kind, i)) for i in cand}
        idx = min(cand, key=lambda i: last_pos[i])
    return idx, rows[idx][2]


def evidence_key(items: list[tuple[str, int]]) -> str:
    """근거 2문장의 요소. 최대 요소 하나, |w|<4 이거나 해·파만이면 '잔잔'."""
    if daily_score.confidence(items) == "약":
        return "잔잔"
    name = daily_score.top_item(items)[0]
    return EVIDENCE_ALIAS.get(name, name)


def rx_element(items: list[tuple[str, int]], grade: str, standout: tuple[str, str] | None) -> str | None:
    """'오늘은 이렇게'의 은행 요소. 보통 날은 None."""
    if grade in CAUTION_GRADES:
        for name, w in sorted(items, key=lambda x: x[1]):
            if w >= 0:
                break
            key = CAUTION_MAP.get(EVIDENCE_ALIAS.get(name, name))
            if key:
                if key in ("day_clash", "month_clash", "day_punish") and standout == ("금전", "주의"):
                    return "wealth_hit"           # 충·형 맞은 글자가 재성이라 금전이 튀는 날
                return key
        return None
    if grade in LUCKY_GRADES:
        for name, w in sorted(items, key=lambda x: -x[1]):
            if w <= 0:
                break
            key = LUCKY_MAP.get(EVIDENCE_ALIAS.get(name, name))
            if key:
                return key
    return None


def compose_rx(account_key: str, d: date, element: str,
               recent: list[tuple[str, str, int]]) -> tuple[str, list[tuple[str, str, int]]]:
    """하지 말 것 1 + 할 것 1 (같은 장면을 앞세움). (문장, 이번에 쓴 [(요소, 구분, 번호)]) 를 돌려준다."""
    i, dont = pick(account_key, d, element, "dont", recent)
    scene = BANK[element]["dont"][i][0]
    j, do = pick(account_key, d, element, "do", recent, scene=scene)
    return f"{dont} {do}", [(element, "dont", i), (element, "do", j)]


def select_for_day(core: MyeongriCoreResult, account_key: str, d: date,
                   recent: list[tuple[str, str, int]], evaluation: dict | None = None) -> dict:
    """하루치 문장 선택. recent 는 그 전 30일에 쓴 (요소, 구분, 번호) 목록."""
    ev = evaluation or daily_score.evaluate(core, daily_score.day_ganji(d), d)
    uses: list[tuple[str, str, int]] = []
    key = evidence_key(ev["items"])
    i, evidence_text = pick(account_key, d, key, "evidence", recent)
    uses.append((key, "evidence", i))
    element = rx_element(ev["items"], ev["grade"], ev["standout"])
    rx_text = None
    if element:
        rx_text, used = compose_rx(account_key, d, element, recent)
        uses.extend(used)
    domain_note = None
    if ev["standout"]:
        domain, kind = ev["standout"]
        j, text = pick(account_key, d, domain, kind, recent)
        uses.append((domain, kind, j))
        domain_note = {"domain": domain, "kind": kind, "text": text}
    return {"evaluation": ev, "evidence_key": key, "evidence_text": evidence_text,
            "rx_element": element, "rx_text": rx_text, "domain_note": domain_note, "uses": uses}


def _history(core: MyeongriCoreResult, account_key: str, start: date, until: date) -> list[tuple[date, tuple[str, str, int]]]:
    """start ~ until(포함) 의 선택 기록을 같은 규칙으로 다시 돌려 복원한다. 계정별로 캐시해 하루씩 이어 붙인다."""
    cache_key = (account_key, repr(core.input))
    cached = _HISTORY_CACHE.get(cache_key)
    if cached and cached["start"] <= start:
        history, cursor = cached["history"], cached["until"]
    else:
        history, cursor = [], start - timedelta(days=1)
    day = cursor + timedelta(days=1)
    while day <= until:
        recent = [u for day_used, u in history if day_used >= day - timedelta(days=RECENT_DAYS)]
        history.extend((day, u) for u in select_for_day(core, account_key, day, recent)["uses"])
        day += timedelta(days=1)
    if len(_HISTORY_CACHE) >= 2048:
        _HISTORY_CACHE.clear()
    _HISTORY_CACHE[cache_key] = {"start": min(start, cached["start"]) if cached and cached["start"] <= start else start,
                                 "until": max(until, cursor), "history": history}
    return history


def render_day(core: MyeongriCoreResult, account_key: str, d: date, evaluation: dict | None = None) -> dict:
    """오늘 문장. 최근 30일 목록은 저장 없이 RX_EPOCH(또는 60일 전) 부터 지난날을 같은 규칙으로 다시 돌려 복원한다.

    시작점을 날짜마다 옮기면(어제는 60일 전부터, 오늘은 59일 전부터) 어제의 복원이 어제 실제로 보인 것과 어긋나
    같은 문장이 이틀 연속 나올 수 있다. 고정된 시작점에서 돌리면 어느 날 계산해도 지난날이 같게 복원된다.
    기록은 계정별 캐시에 하루씩 이어 붙이므로 하루 한 번만 늘어난다(저장이 생기면 그 테이블로 바꾼다).
    """
    cache_key = (account_key, repr(core.input), d.isoformat())
    if cache_key in _RENDER_CACHE:
        return dict(_RENDER_CACHE[cache_key])
    start = min(RX_EPOCH, d - timedelta(days=RECENT_DAYS + REPLAY_WARMUP))
    history = _history(core, account_key, start, d - timedelta(days=1))
    recent = [u for day_used, u in history if d - timedelta(days=RECENT_DAYS) <= day_used < d]
    result = select_for_day(core, account_key, d, recent, evaluation)
    if len(_RENDER_CACHE) >= 4096:
        _RENDER_CACHE.clear()
    _RENDER_CACHE[cache_key] = dict(result)
    return result


_RENDER_CACHE: dict[tuple, dict] = {}
_HISTORY_CACHE: dict[tuple, dict] = {}


def all_sentences() -> list[tuple[str, str]]:
    """검사용: 은행의 모든 문단 (출처, 문단)."""
    out = [(f"EVIDENCE[{k}][{i}]", t) for k, rows in EVIDENCE.items() for i, t in enumerate(rows)]
    out += [(f"DOMAIN[{d}][{k}][{i}]", t) for d, kinds in DOMAIN.items() for k, rows in kinds.items() for i, t in enumerate(rows)]
    out += [(f"BANK[{e}][{k}][{i}]", t) for e, data in BANK.items() for k in ("dont", "do") for i, (_, _, t) in enumerate(data[k])]
    return out
