def all_strings():
    """(은행 이름, 경로, 문자열) 전수. LEAD는 ("scene"|"advice"), 나머지 dict형은 ("text",) 경로가 붙는다."""
    def walk(name, node, path):
        if isinstance(node, str):
            yield name, path, node
        elif isinstance(node, dict):
            for k, v in node.items():
                if k in META_KEYS:
                    continue
                yield from walk(name, v, path + (k,))
        else:
            for i, v in enumerate(node):
                yield from walk(name, v, path + (i,))
    for name, bank in BANKS.items():
        yield from walk(name, bank, ())


