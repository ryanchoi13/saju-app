def compose_extras(*, supplement: str | None, day_element: str | None,
                   year_branch: str | None, day_branch: str | None,
                   avoid: str | None = None, supplement_months: list[int] | None = None) -> list[dict]:
    """새 칸 세 개. 계산에 필요한 값이 없으면 그 칸만 뺀다.
    avoid: 보완 순위 맨 끝 오행(거리를 둘 사람), supplement_months: 보완 기운이 월주에 드는 달."""
    from app.engine.services.annual_touch import element_group as group_of
    from app.engine.shensha import TWELVE_SHENSHA_HANJA, twelve_shensha
    out: list[dict] = []
    if supplement and day_element:
        group = group_of(supplement, day_element)
        if group in PEOPLE:
            paras = [(None, list(PEOPLE[group])), ("어디서 만나나요", list(PEOPLE_WHERE[group]))]
            watch = group_of(avoid, day_element) if avoid and avoid != supplement else None
            if watch in PEOPLE_WATCH and watch != group:
                paras.append(("거리를 둘 사람", list(PEOPLE_WATCH[watch])))
            out.append(_extra("people", "올해 힘이 되는 사람", paras))
    if year_branch and day_branch:
        name = twelve_shensha(day_branch, year_branch)
        if name in SHINSAL_YEAR:
            shown, han = ("도화", "桃花") if name == "년살" else (name, TWELVE_SHENSHA_HANJA[name])
            out.append(_extra("shinsal", "올해의 신살",
                              [(None, [SHINSAL_INTRO, *SHINSAL_YEAR[name]]), ("이렇게 써 보세요", list(SHINSAL_MORE[name]))],
                              note=f"{shown}({han}) · {SHINSAL_GLOSS[name]}"))
    if supplement in GAEWOON:
        el = EL_LABEL[supplement]
        color, direction, habit, item = GAEWOON[supplement]
        food, number, body = GAEWOON_MORE[supplement]
        last = [number]
        months = sorted(set(supplement_months or ()))
        if months and len(months) <= 5:
            shown = "·".join(f"{m}월" for m in months)
            last.append(f"{el} 기운이 드는 {shown}에 미뤄 둔 일을 시작하세요.")
        out.append(_extra("gaewoon", "올해 개운법", [
            (None, [f"올해 채우면 좋은 기운은 {el}입니다.", color, direction]),
            ("생활 속 개운", [habit, item, food, body]),
            ("숫자와 달", last)]))
    return out


def _extra(key, label, paras, note=None):
    """칸 하나: 단락(소제목, 문장들)과 검사용 문장 목록."""
    return dict(key=key, label=label, note=note, paragraphs=paras,
                sentences=[s for _, ss in paras for s in ss])


