def year_shape(grades: dict[int, str]) -> list[str]:
    """월 등급(1~12월 → good/normal/caution)으로 한 해의 앞뒤 모양을 총운에 녹인다. 차이가 없으면 말하지 않는다."""
    def count(key, months):
        return sum(1 for m in months if grades.get(m) == key)
    first, second = range(1, 7), range(7, 13)
    out = []
    g1, g2 = count("good", first), count("good", second)
    c1, c2 = count("caution", first), count("caution", second)
    if g1 - g2 >= 2:
        out.append("좋은 달이 상반기에 더 많으니 하고 싶은 일은 앞쪽에 시작하세요.")
    elif g2 - g1 >= 2:
        out.append("좋은 달이 하반기에 더 많아 뒤로 갈수록 힘이 붙는 해입니다.")
    if c1 - c2 >= 2:
        out.append("주의할 달은 상반기에 몰려 있으니 초반에는 속도를 조절하세요.")
    elif c2 - c1 >= 2:
        out.append("주의할 달은 하반기에 몰려 있으니 큰일은 상반기에 정리해 두세요.")
    return out


