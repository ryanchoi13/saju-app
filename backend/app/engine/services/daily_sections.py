def _pick(pool, seed: int, shift: int):
    return pool[(seed >> shift) % len(pool)]


def enrich_story(story: dict, god: str | None, rel: str | None, seed: int) -> dict:
    """십성이 SECTION_GODS 안이면 총운·카테고리 문단으로 이야기를 바꾼다. 밖이면 그대로 돌려준다."""
    if god not in SECTIONS:
        return story
    data = SECTIONS[god]
    overall = _pick(data["overall"], seed, 5)
    pool = SECONDARY.get(rel or "calm")
    if pool:
        overall = f"{overall}\n\n{_pick(pool, seed, 1)}"   # 화면에서 줄을 나눠 보여 준다(white-space: pre-line)
    sections = [
        {"key": key, "title": title, "body": _pick(data[key], seed, shift)}
        for (key, title), shift in zip(SECTION_ORDER, (2, 3, 4, 6))
    ]
    out = dict(story)
    out.update(
        headline=data["headline"],
        body=overall,
        char_count=len(overall),
        sentence_count=len(split_sentences(overall)),
        sections=sections,
        section_version=SECTION_VERSION,
    )
    return out
