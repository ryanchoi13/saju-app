        direct, indirect = counts['direct_wealth'], counts['indirect_wealth']
        if direct > indirect:
            return '돈을 다루는 기본 성향에서는 계획을 세우고 꾸준히 관리하는 쪽에 무게가 실립니다. 한 번의 큰 기회보다 반복해서 이어갈 수 있는 수입과 지출의 기준을 만드는 데 강점을 살려보세요.'
