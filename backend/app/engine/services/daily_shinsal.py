def is_key(element: str) -> bool:
    return element.startswith(PREFIX)


def rows(element: str, kind: str) -> tuple[tuple[str, str, str], ...]:
    name = element[len(PREFIX):]
    what, tone = kind.split(":")
    if what == "evidence":
        return tuple(("", "", t) for t in EVIDENCE[name][tone])
    return tuple(("", "", t) for t in RX[name][tone][what])


def all_strings():
    """(은행 이름, 경로, 문자열) 전수 — 검사용."""
    for key, lst in TITLE.items():
        for i, t in enumerate(lst):
            yield "TITLE", (key, i), t["text"]
    for key, lst in LEAD.items():
        for i, v in enumerate(lst):
            yield "LEAD", (key, i, "scene"), v["scene"]
            yield "LEAD", (key, i, "advice"), v["advice"]
    for name, tones in EVIDENCE.items():
        for tone, texts in tones.items():
            for i, t in enumerate(texts):
                yield "EVIDENCE", (name, tone, i), t
    for name, tones in RX.items():
        for tone, kinds in tones.items():
            for kind, texts in kinds.items():
                for i, t in enumerate(texts):
                    yield "RX", (name, tone, kind, i), t
    for tone, texts in REASON.items():
        for i, t in enumerate(texts):
            yield "REASON", (tone, i), t
    for name, t in GLOSS.items():
        yield "GLOSS", (name,), t


assert set(_ROWS) == set(TWELVE_SHENSHA) == set(EVIDENCE) == set(RX) == set(GLOSS)
