_BATCHIM = {"木": True, "火": False, "土": False, "金": True, "水": False}


def ga(e: str) -> str:
    return "이" if _BATCHIM[e] else "가"


def copula(e: str) -> str:
    return "이에요" if _BATCHIM[e] else "예요"


def eun(e: str) -> str:
    return "은" if _BATCHIM[e] else "는"


def names(elements: list[str]) -> str:
    return "·".join(ELEMENT_NAME[e] for e in elements)


