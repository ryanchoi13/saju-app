def compose_current(ten_god: str | None, primary_domain: str | None) -> dict:
    """현재 대운 3문단. 알 수 없는 십신/분야는 안전한 기본값으로 대체한다."""
    headline, core, tip = CYCLE_COPY.get(ten_god or "", GENERIC_COPY)
    domain_key = primary_domain if primary_domain in DOMAIN_TIPS else "self"
    return dict(
        schema=SCHEMA,
        headline=headline,
        core=core,
        tip=f"{tip} {DOMAIN_TIPS[domain_key]}",
        copy_ids=[f"cycle:{ten_god if ten_god in CYCLE_COPY else 'generic'}", f"domain:{domain_key}"],
    )


def teaser(start_age: int, ten_god: str | None, current_ten_god: str | None) -> str:
    """다음 대운 한 줄 호기심 문구. 현재와 같은 십신이면 '새 장'이라고 하지 않는다."""
    if ten_god and ten_god == current_ten_god:
        hook = TEASER_SAME
    else:
        hook = TEASER_HOOK.get(ten_god or "", TEASER_UNKNOWN)
    return f"{start_age}세부터 {hook}"
