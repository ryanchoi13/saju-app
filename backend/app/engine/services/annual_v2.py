def compose_month(ledger: CopyLedger, month: int, theme: str, flow: str) -> dict:
    """한 달치 한 단어 + 두 문장. 한 해 안에서 같은 문장을 다시 쓰지 않는다.

    두 문장 = [흐름 문장 또는 보조 주제 문장] + [중심 주제 문장].
    흐름 문장은 풀이 남아 있을 때만 쓰고, 바닥나면 다른 주제의 문장으로 대신한다.
    (같은 흐름이 여러 달 이어져도 문장이 되풀이되지 않게 하기 위해서다.)
    """
    flow = flow if flow in FLOW_LINES else "base"
    themes = tuple(THEME_LINES)
    t_idx = themes.index(theme)
    _, theme_line = ledger.take(f"v2:theme:{theme}", THEME_LINES[theme], offset=month * 5 + t_idx)
    if ledger.has_free(f"v2:flow:{flow}", FLOW_LINES[flow]):
        _, lead = ledger.take(f"v2:flow:{flow}", FLOW_LINES[flow], offset=month * 3)
    else:
        # 보조 주제: 중심 주제가 아니면서 아직 문장이 많이 남은 쪽
        others = [t for t in themes if t != theme]
        second = max(others, key=lambda t: (len(THEME_LINES[t]) - len(ledger._used.get(f"v2:theme:{t}", ())),
                                             -((themes.index(t) - t_idx) % len(themes))))
        _, lead = ledger.take(f"v2:theme:{second}", THEME_LINES[second], offset=month * 5 + themes.index(second))
    return dict(verdict=VERDICTS[flow], flow=flow, theme=theme,
                sentences=[lead, theme_line], text=f"{lead} {theme_line}")


