def central_areas(selection: dict, god: str | None) -> list[dict]:
    """엔진이 짚은 중심 분야를 v2 분야로 바꿔 최대 2개 돌려준다.

    반환: [{"area": "mind", "mode": "base"|"join"|...}, ...]
    근거: selection["primary_domains"](엔진이 같은 순위로 묶은 분야). 없으면 올해 십성의 분야.
    """
    modes = {c["domain"]: c.get("mode", "base") for c in (selection.get("selected") or ())}
    modes.update({c["domain"]: c.get("mode", "base") for c in (selection.get("candidates") or ())
                  if c["domain"] not in modes})
    found: list[dict] = []
    for domain in selection.get("primary_domains") or ():
        area = ENGINE_TO_AREA.get(domain)
        if area and all(f["area"] != area for f in found):
            found.append(dict(area=area, mode=modes.get(domain, "base"), basis="engine"))
        if len(found) == 2:
            break
    if not found and god in GOD_AREA:
        found.append(dict(area=GOD_AREA[god], mode="base", basis="ten_god"))
    return found


def compose_year(selection: dict) -> dict:
    """올해 총운 · 세 가지 · 분야 5칸. 같은 입력이면 항상 같은 결과."""
    god = selection.get("focal_god")
    bank = GODS.get(god, GENERAL)
    centers = central_areas(selection, god if god in GODS else None)
    center_keys = [c["area"] for c in centers]
    mode_of = {c["area"]: c["mode"] for c in centers}

    def block(area: str, central: bool) -> dict:
        short, deep = bank["areas"][area]
        sentences = split_sentences(short)
        if central:
            sentences += split_sentences(deep)
            note = MODE_NOTE.get(area, {}).get(mode_of.get(area, "base"))
            if note:
                sentences += split_sentences(note)
        return dict(area=area, label=AREA_LABEL[area], central=central,
                    mode=mode_of.get(area, "base"), sentences=sentences,
                    text=" ".join(sentences))

    ordered = center_keys + [k for k in AREA_KEYS if k not in center_keys]
    return dict(
        version=COPY_V2_VERSION,
        god=god if god in GODS else None,
        title=bank["title"],
        overview=list(bank["overview"]),
        three=[
            dict(key="best", label="가장 좋은 것", text=bank["best"]),
            dict(key="caution", label="주의할 것", text=bank["caution"]),
            dict(key="advice", label="한 가지 조언", text=bank["advice"]),
        ],
        centers=centers,
        areas=[block(k, k in center_keys) for k in ordered],
    )


