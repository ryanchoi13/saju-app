def _take_if_free(ledger: CopyLedger, key: str, pool: list, offset: int):
    """풀이 남아 있으면 하나 고르고, 바닥났으면 None. (같은 문장을 다시 쓰지 않기 위해 빼는 쪽을 택한다)"""
    if not pool or not ledger.has_free(key, pool):
        return None
    return ledger.take(key, pool, offset)[1]


def compose_month(ledger: CopyLedger, month: int, *, month_god: str | None, year_god: str | None,
                  focus_area: str, flow: str = "base", period: dict | None = None) -> dict:
    """한 달치 풀이. 같은 사람·같은 해에는 항상 같은 글이고, 한 해 안에서 문장을 되풀이하지 않는다."""
    flow = flow if flow in VERDICTS else "base"
    focus_area = focus_area if focus_area in FOCUS else "body"
    god = month_god if month_god in MONTH_FLOW else None

    flow_text = ledger.take(f"m:flow:{god}", MONTH_FLOW[god] if god else GENERAL_FLOW, offset=month)[1]

    link = None
    if god and year_god in FAMILY:
        relation = family_relation(year_god, god)
        template = ledger.take(f"m:link:{relation}", LINK[relation], offset=month)[1]
        link = template.format(m=month, Y=YEAR_PHRASE[year_god], M=MONTH_PHRASE[god])

    focus = ledger.take(f"m:focus:{focus_area}", FOCUS[focus_area], offset=month * 3)[1]
    mode_line = _take_if_free(ledger, f"m:mode:{flow}", MODE_LINES.get(flow, []), month * 2)
    focus_sentences = split_sentences(focus) + ([mode_line] if mode_line else [])

    family = FAMILY.get(god, "peer") if god else None
    lines = []
    for area in AREA_KEYS:
        if area == focus_area or family is None:
            continue
        text = _take_if_free(ledger, f"m:area:{family}:{area}", AREA_LINES[family][area], month)
        if text:
            lines.append(dict(area=area, label=MONTH_AREA_LABEL[area], text=text))

    pairs = [f"{d}\t{a}" for d, a in (DO_AVOID[god] if god else GENERAL_DO_AVOID)]
    do, avoid = ledger.take(f"m:do:{god}", pairs, offset=month)[1].split("\t")

    period_text = None
    if period:
        s, e = period["start"], period["end"]
        period_text = f"{s.month}월 {s.day}일({period['name']})부터 {e.month}월 {e.day}일까지의 흐름입니다."

    sentences = [*split_sentences(flow_text), *(split_sentences(link) if link else []),
                 *focus_sentences, *[l["text"] for l in lines]]
    return dict(
        verdict=VERDICTS[flow], flow=flow, god=god, period=period_text,
        flow_text=flow_text, link=link,
        focus=dict(area=focus_area, label=AREA_LABEL[focus_area], text=" ".join(focus_sentences)),
        lines=lines, do=do, avoid=avoid, sentences=sentences,
    )


def validate_month(reading: dict) -> list[str]:
    issues = []
    for s in reading["sentences"] + [reading["do"], reading["avoid"]]:
        if len(s) > SENTENCE_MAX_MONTH:
            issues.append(f"문장이 깁니다({len(s)}): {s}")
        if find_banned(s):
            issues.append(f"금기어 {find_banned(s)}: {s}")
        for w in HEDGES:
            if w in s:
                issues.append(f"얼버무림 '{w}': {s}")
    if len(reading["sentences"]) < 8:
        issues.append(f"문장 수가 적습니다({len(reading['sentences'])})")
    return issues


