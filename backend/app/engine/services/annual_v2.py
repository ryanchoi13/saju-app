def family_relation(year_god: str, month_god: str) -> str:
    """올해 십성 계열과 그달 십성 계열의 관계: same / feeds / fed / controls / controlled."""
    i, j = FAMILY_ORDER.index(FAMILY[year_god]), FAMILY_ORDER.index(FAMILY[month_god])
    if i == j:
        return "same"
    if (i + 1) % 5 == j:
        return "feeds"       # 올해의 힘이 그달로 흘러감(생)
    if (j + 1) % 5 == i:
        return "fed"         # 그달이 올해에 힘을 보탬
    if (i + 2) % 5 == j:
        return "controls"    # 올해가 그달을 다잡음(극)
    return "controlled"      # 그달이 올해에 제동(피극)


