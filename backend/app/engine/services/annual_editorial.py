def role_family(god):
    if god in {"peer", "rob_wealth"}:
        return "peer"
    if god in {"eating_god", "hurting_officer"}:
        return "output"
    if god in {"direct_wealth", "indirect_wealth"}:
        return "wealth"
    if god in {"direct_officer", "seven_killings"}:
        return "officer"
    return "resource"


def scene(candidate):
    options = SCENES.get(candidate["domain"], SCENES["self"])
    return options.get(candidate.get("mode"), options["base"])
