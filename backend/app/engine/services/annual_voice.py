def hashtags(day_label: str | None, title: str | None, center_label: str | None) -> list[str]:
    """해시태그 셋: 일간 그림 · 올해 제목 · 올해의 중심 분야."""
    tags = [day_label, title, f"올해의 중심은 {center_label}" if center_label else None]
    return ["#" + t.replace(" ", "") for t in tags if t]
