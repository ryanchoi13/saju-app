def validate_month(reading: dict) -> list[str]:
    """규격 위반을 문자열 리스트로 돌려준다. 비어 있으면 통과."""
    issues: list[str] = []
    hero, subs, headline = reading["hero"], reading["subs"], reading["headline"]

    lo, hi = SPEC["hero_chars"]
    n = len(hero["body"])
    if not lo <= n <= hi:
        issues.append(f"hero 글자 수 {n} (허용 {lo}~{hi})")
    sents = split_sentences(hero["body"])
    slo, shi = SPEC["hero_sentences"]
    if not slo <= len(sents) <= shi:
        issues.append(f"hero 문장 수 {len(sents)} (허용 {slo}~{shi})")
    if len(headline) > SPEC["headline_max"] or "\n" in headline:
        issues.append(f"헤드라인 길이/줄바꿈 문제: {headline!r}")

    if len(subs) != 3:
        issues.append(f"sub 개수 {len(subs)} (필요 3)")
    if hero["theme"] in {s["theme"] for s in subs}:
        issues.append("hero 테마가 sub에도 들어 있음")
    clo, chi = SPEC["sub_chars"]
    for s in subs:
        if not clo <= len(s["note"]) <= chi:
            issues.append(f"sub[{s['theme']}] 글자 수 {len(s['note'])} (허용 {clo}~{chi})")
        if len(split_sentences(s["note"])) != 1:
            issues.append(f"sub[{s['theme']}] 문장 수가 1이 아님")
    total = sum(len(s["note"]) for s in subs)
    tlo, thi = SPEC["sub_total"]
    if not tlo <= total <= thi:
        issues.append(f"sub 합계 {total} (허용 {tlo}~{thi})")

    for t in [headline, hero["body"], *[s["note"] for s in subs]]:
        banned = find_banned(t)
        if banned:
            issues.append(f"금기어 {banned}: {t[:24]}…")

    # 같은 달 안에서 문장 머리말(앞 3글자)이 겹치면 템플릿 반복처럼 읽힌다.
    heads = [_prefix(x) for x in [*sents, *[s["note"] for s in subs]]]
    dup = sorted({h for h in heads if heads.count(h) > 1})
    if dup:
        issues.append(f"같은 달 문장 머리말 반복 {dup}")
    return issues


def audit_year(readings: list[dict], similarity: float | None = None) -> list[str]:
    """12개월 전체에서 같은 문장이 있는지 본다. similarity를 주면 거의 같은 문장(예: 0.85 이상)도 찾는다(느림)."""
    issues: list[str] = []
    seen: dict[str, int] = {}
    pool: list[tuple[int, str]] = []
    for idx, r in enumerate(readings):
        items = [r["headline"], *split_sentences(r["hero"]["body"]), *[s["note"] for s in r["subs"]]]
        for t in items:
            if t in seen:
                issues.append(f"문장 반복: {t!r} ({seen[t] + 1}번째 달과 {idx + 1}번째 달)")
            seen.setdefault(t, idx)
            pool.append((idx, t))
    if similarity is None:
        return issues
    for a in range(len(pool)):
        for b in range(a + 1, len(pool)):
            if pool[a][1] == pool[b][1]:
                continue
            if SequenceMatcher(None, pool[a][1], pool[b][1]).ratio() >= similarity:
                issues.append(f"거의 같은 문장: {pool[a][1]!r} ≈ {pool[b][1]!r}")
    return issues
