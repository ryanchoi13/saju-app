def _prefix(text: str) -> str:
    return text.strip()[:3]


class CopyLedger:
    """한 번의 리포트(한 사용자·한 해) 안에서 어떤 문장을 이미 썼는지 기록한다."""

    def __init__(self, seed: int = 0):
        self.seed = int(seed)
        self._used: dict[str, set[int]] = {}
        self.reused: list[tuple[str, int]] = []  # 풀이 바닥나 어쩔 수 없이 다시 쓴 경우 (정상이라면 비어 있다)

    def has_free(self, key: str, pool: list[str]) -> bool:
        return len(self._used.get(key, ())) < len(pool)

    def take(
        self,
        key: str,
        pool: list[str],
        offset: int,
        avoid_family: str | None = None,
        avoid_prefixes: frozenset | set = frozenset(),
    ) -> tuple[int, str]:
        """아직 안 쓴 문장 하나를 고른다. 이웃 문장과 어미 계열·머리말이 겹치지 않는 쪽을 먼저 고른다."""
        n = len(pool)
        used = self._used.setdefault(key, set())
        start = (self.seed + offset) % n
        order = [(start + i) % n for i in range(n)]
        free = [i for i in order if i not in used]
        if free:
            ok_prefix = [i for i in free if _prefix(pool[i]) not in avoid_prefixes]
            ok_both = [i for i in ok_prefix if avoid_family is None or ending_family(pool[i]) != avoid_family]
            pick = (ok_both or ok_prefix or free)[0]
        else:
            pick = start
            self.reused.append((key, pick))
            logger.warning("카피 풀 소진 key=%s — 문장을 재사용합니다", key)
        used.add(pick)
        return pick, pool[pick]


def seed_from(*parts) -> int:
    """같은 입력이면 항상 같은 정수. (파이썬 hash()는 실행마다 달라지므로 crc32를 쓴다.)"""
    return zlib.crc32("|".join(str(p) for p in parts).encode("utf-8")) % 100003


def flow_of(mode: str | None) -> str:
    return mode if mode in FLOWS else "base"


def compose_month(ledger: CopyLedger, month: int, hero_theme: str, flow: str = "base") -> dict:
    """한 달치 Hero(60%) + Sub 3개(40%)를 만든다. 근거 정보(kind·source_ids)는 호출한 쪽에서 덧붙인다."""
    if hero_theme not in HERO_PARTS:
        raise ValueError(f"알 수 없는 테마: {hero_theme}")
    t_idx = THEME_KEYS.index(hero_theme)
    parts = HERO_PARTS[hero_theme]

    sentences: list[str] = []
    copy_ids: list[str] = []
    prefixes: set[str] = set()

    open_key = flow if flow in OPEN and flow != "base" and ledger.has_free(f"open:{flow}", OPEN[flow]) else "base"
    i, text = ledger.take(f"open:{open_key}", OPEN[open_key], offset=month * 5)
    sentences.append(text)
    prefixes.add(_prefix(text))
    copy_ids.append(f"open:{open_key}:{i}")

    # 장면(scene)은 따로 고르고, 주의(caution)와 팁(tip)은 같은 번호로 묶어 한 세트로 뽑는다.
    # (헌법: 주의점을 짚으면 그 주의점에 맞는 오늘의 팁을 함께 준다. 두 풀은 번호가 서로 짝이다.)
    key = f"{hero_theme}:scene"
    i, text = ledger.take(
        key, parts["scene"], offset=month * 5 + t_idx,
        avoid_family=ending_family(sentences[-1]), avoid_prefixes=prefixes,
    )
    sentences.append(text)
    prefixes.add(_prefix(text))
    copy_ids.append(f"{key}:{i}")

    key = f"{hero_theme}:pair"
    i, caution = ledger.take(
        key, parts["caution"], offset=month * 7 + 3 + t_idx,
        avoid_family=ending_family(sentences[-1]), avoid_prefixes=prefixes,
    )
    tip = parts["tip"][i]
    sentences.extend([caution, tip])
    prefixes.update((_prefix(caution), _prefix(tip)))
    copy_ids.append(f"{key}:{i}")

    body = " ".join(sentences)

    i, headline = ledger.take(f"headline:{hero_theme}", HEADLINES[hero_theme], offset=month * 7 + 2)
    copy_ids.append(f"headline:{hero_theme}:{i}")

    subs = []
    seen_beop = any(ending_family(x) == "beop" for x in sentences)
    for theme in THEME_KEYS:
        if theme == hero_theme:
            continue
        i, note = ledger.take(
            f"sub:{theme}",
            SUB_NOTES[theme],
            offset=month * 5 + THEME_KEYS.index(theme) * 3 + 1,
            avoid_family="beop" if seen_beop else None,
            avoid_prefixes=prefixes,
        )
        seen_beop = seen_beop or ending_family(note) == "beop"
        prefixes.add(_prefix(note))
        copy_ids.append(f"sub:{theme}:{i}")
        subs.append(dict(theme=theme, label=THEME_LABEL[theme], note=note, char_count=len(note)))

    return dict(
        schema=SCHEMA,
        headline=headline,
        hero=dict(
            theme=hero_theme,
            label=THEME_LABEL[hero_theme],
            body=body,
            char_count=len(body),
            sentence_count=len(sentences),
        ),
        subs=subs,
        copy_ids=copy_ids,
    )


