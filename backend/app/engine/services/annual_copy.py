_BANNED_SOURCES = (
    r"작업\s*시간",
    r"시간\s*단축",
    r"(?<![가-힣])단축",
    r"(?<![가-힣])실적",
    r"(?<![가-힣])성과",
    r"(?<![가-힣])정산",
    r"(?<![가-힣])몫",
    r"(?<![가-힣])한도",
    r"(?<![가-힣])대우",
    r"(?<![가-힣])처우",
    r"인사\s*고과",
    r"(?<![가-힣])고과",
    r"(?<![가-힣])기여도",
    r"(?<![가-힣])생산성",
    r"KPI",
)
BANNED_PATTERNS = tuple(re.compile(p) for p in _BANNED_SOURCES)


def find_banned(text: str) -> list[str]:
    """text 안에서 걸린 금기어를 돌려준다. 없으면 빈 리스트."""
    found = []
    for pattern in BANNED_PATTERNS:
        m = pattern.search(text or "")
        if m:
            found.append(m.group(0))
    return found


_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+")


def split_sentences(text: str) -> list[str]:
    return [s for s in _SENT_SPLIT.split((text or "").strip()) if s]


def ending_family(sentence: str) -> str:
    """종결어미 계열. 리듬 점검용: formal(~합니다) / soft(~해요) / try(~해보세요) / beop(~인 법이죠)."""
    s = sentence.strip().rstrip(".!? ")
    if s.endswith("법이죠"):
        return "beop"
    if s.endswith("세요"):
        return "try"
    if s.endswith("니다"):
        return "formal"
    if s.endswith("요"):
        return "soft"
    return "other"


def sanitize_paragraph(text: str, fallback: str = "", where: str = "") -> str:
    """엔진 밖(annual_editorial 등)에서 온 문단을 통과시키는 안전망.

    금기어가 든 문장만 덜어낸다. 문단이 통째로 비면 fallback을 쓴다.
    걸리지 않으면 원문을 한 글자도 바꾸지 않고 돌려준다.
    """
    if not text:
        return fallback
    sentences = split_sentences(text)
    kept = [s for s in sentences if not find_banned(s)]
    if len(kept) == len(sentences):
        return text
    logger.warning(
        "금기어 문장 제외 where=%s terms=%s",
        where or "-",
        sorted({t for s in sentences for t in find_banned(s)}),
    )
    return " ".join(kept) if kept else fallback


